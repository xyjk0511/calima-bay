export function getDistrictAt(x, z) {
  if (x > 142) return DISTRICTS[5];
  if (x >= 44 && z >= -140 && z <= 170) return DISTRICTS[0];
  if (z < -140 && x >= -130) return DISTRICTS[4];
  if (z > 84 && x < 142) return DISTRICTS[2];
  if (x < -82 && z <= 84) return DISTRICTS[3];
  return DISTRICTS[1];
}

